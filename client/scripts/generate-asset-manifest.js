/**
 * Scans client/public/assets and writes client/src/generated/asset-manifest.js.
 *
 * To add a future asset:
 *   1. Place the file under client/public/assets in the expected folder
 *      (profile/, resume/, projects/<slug>/).
 *   2. Use the expected filename (profile-portrait.webp,
 *      profile-portrait-square.webp, jahid-hasan-resume.pdf, cover.<ext>,
 *      screenshot-01.<ext>, screenshot-02.<ext>, ...).
 *   3. Restart `npm run dev` (or run `npm run build`).
 *   4. The manifest regenerates automatically via the predev/prebuild hook.
 */
import { readdirSync, statSync, mkdirSync, writeFileSync } from "node:fs";
import { join, dirname, extname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const CLIENT_ROOT = join(__dirname, "..");
const ASSETS_DIR = join(CLIENT_ROOT, "public", "assets");
const OUTPUT_FILE = join(CLIENT_ROOT, "src", "generated", "asset-manifest.js");

const SUPPORTED_EXTENSIONS = [
  ".webp",
  ".jpg",
  ".jpeg",
  ".png",
  ".avif",
  ".svg",
];

const PLACEHOLDERS = {
  profile: "/assets/placeholders/profile-placeholder.svg",
  projectCover: "/assets/placeholders/project-cover-placeholder.svg",
  projectScreenshot: "/assets/placeholders/project-screenshot-placeholder.svg",
};

function listFiles(dir) {
  try {
    return readdirSync(dir).filter((name) => {
      const full = join(dir, name);
      return statSync(full).isFile();
    });
  } catch {
    return [];
  }
}

function findByBaseName(dir, baseName) {
  const files = listFiles(dir);
  const match = files
    .filter((name) =>
      SUPPORTED_EXTENSIONS.includes(extname(name).toLowerCase()),
    )
    .find(
      (name) => name.slice(0, name.length - extname(name).length) === baseName,
    );
  return match ?? null;
}

function buildProfilePortrait(baseName) {
  const dir = join(ASSETS_DIR, "profile");
  const file = findByBaseName(dir, baseName);
  return file
    ? {
        available: true,
        src: `/assets/profile/${file}`,
        fallback: PLACEHOLDERS.profile,
      }
    : { available: false, src: null, fallback: PLACEHOLDERS.profile };
}

function buildResume() {
  const dir = join(ASSETS_DIR, "resume");
  const files = listFiles(dir).filter(
    (name) => extname(name).toLowerCase() === ".pdf",
  );
  const file = files.includes("jahid-hasan-resume.pdf")
    ? "jahid-hasan-resume.pdf"
    : (files.sort()[0] ?? null);
  return file
    ? { available: true, src: `/assets/resume/${file}` }
    : { available: false, src: null };
}

function buildProjectCover(slug) {
  const dir = join(ASSETS_DIR, "projects", slug);
  const file = findByBaseName(dir, "cover");
  return file
    ? {
        available: true,
        src: `/assets/projects/${slug}/${file}`,
        fallback: PLACEHOLDERS.projectCover,
      }
    : { available: false, src: null, fallback: PLACEHOLDERS.projectCover };
}

function buildProjectGallery(slug) {
  const dir = join(ASSETS_DIR, "projects", slug);
  const files = listFiles(dir)
    .filter((name) =>
      SUPPORTED_EXTENSIONS.includes(extname(name).toLowerCase()),
    )
    .filter((name) => /^screenshot-\d+\./i.test(name))
    .sort();
  return files.map((file) => ({
    file,
    src: `/assets/projects/${slug}/${file}`,
  }));
}

function buildManifest() {
  const projectSlugDirs = {
    sarabo: "sarabo",
    bangLearner: "bang-learner",
    noteBank: "note-bank",
  };

  const projects = Object.fromEntries(
    Object.entries(projectSlugDirs).map(([key, slug]) => [
      key,
      {
        cover: buildProjectCover(slug),
        gallery: buildProjectGallery(slug),
      },
    ]),
  );

  return {
    profile: {
      portrait: buildProfilePortrait("profile-portrait"),
      portraitSquare: buildProfilePortrait("profile-portrait-square"),
    },
    resume: buildResume(),
    projects,
  };
}

function serialize(value, indent = 0) {
  const pad = "  ".repeat(indent);
  const childPad = "  ".repeat(indent + 1);

  if (Array.isArray(value)) {
    if (value.length === 0) return "[]";
    const items = value.map(
      (item) => `${childPad}${serialize(item, indent + 1)}`,
    );
    return `[\n${items.join(",\n")},\n${pad}]`;
  }

  if (value && typeof value === "object") {
    const keys = Object.keys(value);
    if (keys.length === 0) return "{}";
    const entries = keys.map(
      (key) => `${childPad}${key}: ${serialize(value[key], indent + 1)}`,
    );
    return `{\n${entries.join(",\n")},\n${pad}}`;
  }

  return JSON.stringify(value);
}

function generate() {
  const manifest = buildManifest();
  const banner =
    "// AUTO-GENERATED by client/scripts/generate-asset-manifest.js — do not edit by hand.\n" +
    "// Regenerate with `npm run assets:sync` (also runs automatically before dev/build/test).\n";
  const contents = `${banner}\nexport const assetManifest = ${serialize(manifest)};\n`;

  mkdirSync(dirname(OUTPUT_FILE), { recursive: true });
  writeFileSync(OUTPUT_FILE, contents, "utf8");

  return manifest;
}

export {
  buildManifest,
  buildProfilePortrait,
  buildResume,
  buildProjectCover,
  buildProjectGallery,
  serialize,
  ASSETS_DIR,
};

const isMainModule =
  process.argv[1] &&
  fileURLToPath(import.meta.url) === resolve(process.argv[1]);

if (isMainModule) {
  const manifest = generate();
  console.log(
    `Asset manifest written to ${OUTPUT_FILE.replace(CLIENT_ROOT, "client")} (profile: ${manifest.profile.portrait.available ? "found" : "missing"}, resume: ${manifest.resume.available ? "found" : "missing"}, sarabo gallery: ${manifest.projects.sarabo.gallery.length} image(s)).`,
  );
}
